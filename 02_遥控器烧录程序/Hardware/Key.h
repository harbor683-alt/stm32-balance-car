/***************************************************************************************
  * 模块名称：			Key.h（按键扫描驱动头文件，遥控器端工程）
  * 模块功能：			对外声明Key.c提供的3个函数
  * 使用流程：			main函数中调用Key_Init()一次 → TIM1的1ms中断中周期调用Key_Tick()
  * 						（完成20ms消抖和松手检测）→ 主循环中调用Key_GetNum()取走键码（读后清零）
  * 键码范围：			0表示无按键事件，1~12对应遥控器的12个独立按键
  ***************************************************************************************
  */

#ifndef __KEY_H
#define __KEY_H

/*按键初始化：开启GPIOA/GPIOB时钟，把12个按键所在引脚配置为内部上拉输入（低电平有效），无参数无返回值*/
void Key_Init(void);

/*读取键码（读后清零）：返回1~12表示最近发生的一次松手按键事件，返回0表示没有新按键；
  调用一次后键码自动清零，保证同一次按键不会被重复读取*/
uint8_t Key_GetNum(void);

/*按键节拍函数：必须每隔1ms被定时中断调用一次；内部每20ms采样一次按键电平并做松手检测，无参数无返回值*/
void Key_Tick(void);

#endif
