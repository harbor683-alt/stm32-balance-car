/***************************************************************************************
  * 模块名称：			AD.h（ADC模数转换驱动头文件，遥控器端工程）
  * 模块功能：			对外声明AD.c提供的两个函数，其他文件（如main.c）包含本头文件后即可调用
  * 使用方法：			上电先调用一次AD_Init()完成初始化；之后在主循环中反复调用
  * 						AD_GetValue(ADC_Channel_0~3)读取PA0~PA3四路摇杆的原始AD值
  ***************************************************************************************
  */

#ifndef __AD_H
#define __AD_H

/*AD初始化函数：开启ADC1/GPIOA时钟、配置模拟输入引脚、配置ADC工作方式并执行自校准，无参数无返回值*/
void AD_Init(void);

/*获取指定通道一次AD转换的结果
  参数：ADC_Channel，要转换的通道，本工程只用ADC_Channel_0/1/2/3（对应PA0/PA1/PA2/PA3）
  返回值：uint16_t类型，转换结果0~4095（12位分辨率），摇杆回中时约为2048*/
uint16_t AD_GetValue(uint8_t ADC_Channel);

#endif
