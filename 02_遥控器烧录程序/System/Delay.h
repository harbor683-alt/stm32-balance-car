/***************************************************************************************
  * 模块名称：			Delay.h（延时驱动头文件，遥控器端工程）
  * 模块功能：			声明三个阻塞式延时函数，基于Cortex-M3内核的SysTick滴答定时器实现
  * 注意事项：			延时期间CPU停在函数内部等待，不会执行主循环代码，因此长延时应谨慎使用；
  * 						本工程周期性任务（1ms按键扫描、100ms无线发包）靠TIM1中断而非本延时
  ***************************************************************************************
  */

#ifndef __DELAY_H
#define __DELAY_H

/*微秒级延时，参数xus范围0~233015（受SysTick 24位计数器宽度限制）*/
void Delay_us(uint32_t us);
/*毫秒级延时，参数ms范围0~4294967295（内部循环调用微秒延时）*/
void Delay_ms(uint32_t ms);
/*秒级延时，参数s范围0~4294967295（内部循环调用毫秒延时）*/
void Delay_s(uint32_t s);

#endif
