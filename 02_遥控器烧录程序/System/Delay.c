/***************************************************************************************
  * 模块名称：			Delay.c（SysTick系统滴答定时器延时驱动，遥控器端工程）
  * 模块功能：			提供微秒/毫秒/秒三级阻塞式延时函数，供OLED初始化等待等场合使用
  * 原理一句话：			Cortex-M3内核自带一个24位倒计数定时器SysTick，让它按固定时钟数倒数，
  * 						程序死等它数到0（查询COUNTFLAG标志），数完的时间就是精确延时
  * 在本工程的地位：		主循环的100ms发送节拍并不使用本延时（那是TIM1硬件定时中断干的），
  * 						本模块主要用于软件I2C时序、上电等待等需要短暂死等的地方
  ***************************************************************************************
  */

#include "stm32f10x.h"

/**
  * @brief  微秒级延时
  * @param  xus 延时时长，范围：0~233015
  * @retval 无
  */
void Delay_us(uint32_t xus)
{
	/*【知识点·SysTick四个寄存器】*/
	/*LOAD是24位重装值：系统主频72MHz时，数72下正好1微秒，所以延时xus微秒就装入72*xus；*/
	/*72*xus不能超过2^24-1=16777215，反推xus最大约233015，这就是参数上限的由来。*/
	/*CTRL=0x05：bit0 ENABLE=1启动定时器，bit2 CLKSOURCE=1选择HCLK(72MHz)作为时钟源；*/
	/*bit16 COUNTFLAG：计数器倒数到0时由硬件置1，while查询到它为1即表示时间到；读CTRL或清零会使其复位。*/
	SysTick->LOAD = 72 * xus;				//设置定时器重装值
	SysTick->VAL = 0x00;					//清空当前计数值
	SysTick->CTRL = 0x00000005;				//设置时钟源为HCLK，启动定时器
	while(!(SysTick->CTRL & 0x00010000));	//等待计数到0
	SysTick->CTRL = 0x00000004;				//关闭定时器
}

/**
  * @brief  毫秒级延时
  * @param  xms 延时时长，范围：0~4294967295
  * @retval 无
  */
void Delay_ms(uint32_t xms)
{
	/*毫秒延时不在一次SysTick里装72000*xms（会超出24位上限），而是复用微秒函数循环xms次，
	  每次延时1000us，这样延时长度理论上只受uint32_t范围限制*/
	while(xms--)
	{
		Delay_us(1000);
	}
}
 
/**
  * @brief  秒级延时
  * @param  xs 延时时长，范围：0~4294967295
  * @retval 无
  */
void Delay_s(uint32_t xs)
{
	while(xs--)
	{
		Delay_ms(1000);
	}
} 
