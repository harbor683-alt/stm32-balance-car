/***************************************************************************************
  * 文件名称：MPU6050.h
  * 功    能：MPU6050六轴姿态传感器驱动的头文件，对外暴露寄存器读写、初始化、
  *           读ID和批量获取姿态数据的函数声明。
  * 使用方法：在需要姿态数据的文件中 #include "MPU6050.h"，先调用一次
  *           MPU6050_Init()初始化，之后周期性（本工程每10ms）调用
  *           MPU6050_GetData()即可拿到加速度与陀螺仪原始值。
  * 依赖关系：内部依赖MyI2C（软件I2C）和MPU6050_Reg.h（寄存器地址表），
  *           调用者无需关心底层I2C时序。
  ***************************************************************************************
  */
#ifndef __MPU6050_H
#define __MPU6050_H

/*---- 底层寄存器读写（一般由本驱动内部使用，也可用于直接调试某个寄存器）----*/
void MPU6050_WriteReg(uint8_t RegAddress, uint8_t Data);	//写单个寄存器：寄存器号，写入值
uint8_t MPU6050_ReadReg(uint8_t RegAddress);				//读单个寄存器：寄存器号，返回读到的值

/*---- 上层常用接口 ----*/
void MPU6050_Init(void);	//MPU6050初始化（唤醒、时钟源、采样率、±16g、±2000dps）
uint8_t MPU6050_GetID(void);	//读WHO_AM_I身份寄存器，正常返回0x68，可用于检测通信
/*一次性读取6个轴的16位有符号原始值：前3个为加速度XYZ，后3个为陀螺仪XYZ；
  参数均为指针（输出参数），函数内部把结果写入调用者提供的变量*/
void MPU6050_GetData(int16_t *AccX, int16_t *AccY, int16_t *AccZ, 
						int16_t *GyroX, int16_t *GyroY, int16_t *GyroZ);

#endif
