/**
  **********************************************************************
  * @file    Delay.c
  * @brief   延时模块：提供微秒(us)、毫秒(ms)、秒(s)三级阻塞式延时
  * @hardware 使用Cortex-M3内核自带的SysTick（系统滴答定时器），
  *          它是一个24位的递减计数器，属于内核外设，不占用TIM1等
  *          通用/高级定时器资源
  * @role    系统最底层的"时间工具"。软件I2C时序、OLED刷新间隔、
  *          按键消抖、开机界面停留、调试模式闪烁提示等都要靠它等待
  * @note    本工程主频72MHz，SysTick每计数1次耗时 1/72MHz≈0.0139us，
  *          计数72次恰好为1us，这就是下面重装值写成"72 * xus"的原因
  **********************************************************************
  */
#include "stm32f10x.h"

/**
  * @brief  微秒级延时
  * @param  xus 延时时长，范围：0~233015
  * @retval 无
  * @note   阻塞式延时：延时期间CPU停在while处等待，不做其他事情
  */
void Delay_us(uint32_t xus)
{
	/* 重装值=72*xus：72MHz下数72个脉冲是1us，数72*xus个脉冲就是xus微秒 */
	/* SysTick为24位计数器，LOAD最大可填2^24-1=16777215， */
	/* 故xus最大约16777215/72≈233015，超出范围定时会不准 */
	SysTick->LOAD = 72 * xus;				//设置定时器重装值
	SysTick->VAL = 0x00;					//清空当前计数值
	/*（补充）清空VAL后计数器自动从LOAD重新开始倒数，保证每次定时都从满值开始 */
	SysTick->CTRL = 0x00000005;				//设置时钟源为HCLK，启动定时器
	/* CTRL寄存器各位含义：bit0=ENABLE(1=启动计数器)，bit2=CLKSOURCE(1=选择内核时钟HCLK=72MHz) */
	/* 0x00000005即bit0、bit2为1，注意此处不开中断，只用查询方式 */
	while(!(SysTick->CTRL & 0x00010000));	//等待计数到0
	/* bit16是COUNTFLAG标志位：计数器数到0时由硬件自动置1，读到该位为1说明定时时间到 */
	SysTick->CTRL = 0x00000004;				//关闭定时器
	/* 0x00000004即bit0写0，关闭计数器；每次用完即关，下次重新配置，互不干扰 */
}

/**
  * @brief  毫秒级延时
  * @param  xms 延时时长，范围：0~4294967295
  * @retval 无
  * @note   1ms=1000us。不直接把LOAD一次填成72000*xms，是因为SysTick
  *         只有24位、一次最多装16777215；拆成"循环xms次、每次延1000us"
  *         就可以延时任意时长，uint32_t范围内理论可延约49.7天
  */
void Delay_ms(uint32_t xms)
{
	while(xms--)		//先判断xms是否为0，再自减：循环xms次，每次延时1毫秒
	{
		Delay_us(1000);	//复用微秒延时，延时1000us即1ms
	}
}
 
/**
  * @brief  秒级延时
  * @param  xs 延时时长，范围：0~4294967295
  * @retval 无
  * @note   同样采用逐级复用的写法：1秒=1000毫秒，循环xs次即可
  */
void Delay_s(uint32_t xs)
{
	while(xs--)
	{
		Delay_ms(1000);	//复用毫秒延时，延时1000ms即1s
	}
} 
