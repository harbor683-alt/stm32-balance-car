#ifndef __DELAY_H		//头文件包含卫士：防止被重复包含导致函数重复声明
#define __DELAY_H

void Delay_us(uint32_t us);	//微秒级延时，参数us：要延时的微秒数（最大约233015）
void Delay_ms(uint32_t ms);	//毫秒级延时，参数ms：要延时的毫秒数
void Delay_s(uint32_t s);	//秒级延时，参数s：要延时的秒数

#endif
